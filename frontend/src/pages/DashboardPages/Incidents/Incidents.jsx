import React, { useEffect, useMemo, useState } from "react";
import PageLayout from "../../../layout/PageLayout";
import { useOutletContext } from "react-router";
import { Search } from "lucide-react";
import { Cards, EventCard, Button } from "../../../components";
import { events } from "../../../TestData";

const PAGE_WINDOW_SIZE = 5;
const PAGE_SIZE = 6;
const UNASSIGNED_FILTER = "__unassigned__";

function Incidents() {
  const setActivePage = useOutletContext();
  const [currentPage, setCurrentPage] = useState(1);
  const [eventsPerPage, setEventsPerPage] = useState(6);
  const [severityFilter, setSeverityFilter] = useState("all");
  const [statusFilter, setStatusFilter] = useState("all");
  const [assigneeFilter, setAssigneeFilter] = useState("all");
  const [searchQuery, setSearchQuery] = useState("");
  const [unassigned, setUnassigned] = useState(0);
  const [investigating, setInvestigating] = useState(0);
  const [blocked, setBlocked] = useState(0);

  // Replace this local fixture with the event-stream data source when the API
  const eventData = events; //change it when data comes form backend

  const assignees = [
    ...new Set(
      eventData.map((event) => event.securityOfficer?.trim()).filter(Boolean),
    ),
  ].sort((first, second) => first.localeCompare(second));
  const hasUnassignedIncidents = eventData.some(
    (event) => !event.securityOfficer?.trim(),
  );

  const filterData = useMemo(() => {
    const query = searchQuery.trim().toLowerCase();

    return eventData.filter((event) => {
      const matchesSeverity =
        severityFilter === "all" || event.threatLevel === severityFilter;
      const matchesStatus =
        statusFilter === "all" || event.status === statusFilter;
      const matchesAssignee =
        assigneeFilter === "all" ||
        (assigneeFilter === UNASSIGNED_FILTER
          ? !event.securityOfficer?.trim()
          : event.securityOfficer === assigneeFilter);
      const matchesSearch =
        !query ||
        [
          event.id,
          event.description,
          event.asset,
          event.ip,
          event.location,
          event.user,
          event.role,
          event.securityOfficer,
          event.officerRole,
          event.status,
          event.threatLevel,
        ].some((value) =>
          String(value ?? "")
            .toLowerCase()
            .includes(query),
        );

      return (
        matchesSeverity && matchesStatus && matchesAssignee && matchesSearch
      );
    });
  }, [eventData, severityFilter, statusFilter, assigneeFilter, searchQuery]);

  const totalPages = Math.ceil(filterData.length / eventsPerPage);
  const firstEventIndex = (currentPage - 1) * eventsPerPage;
  const currentEvents = filterData.slice(
    firstEventIndex,
    firstEventIndex + eventsPerPage,
  );
  const firstVisiblePage = Math.max(
    1,
    Math.min(
      currentPage - Math.floor(PAGE_WINDOW_SIZE / 2),
      totalPages - PAGE_WINDOW_SIZE + 1,
    ),
  );
  const visiblePages = Array.from(
    {
      length: Math.min(PAGE_WINDOW_SIZE, totalPages),
    },
    (_, index) => firstVisiblePage + index,
  );

  useEffect(() => {
    setCurrentPage(1);
  }, [severityFilter, statusFilter, assigneeFilter, searchQuery]);

  useEffect(() => {
    setActivePage(2);
    setUnassigned(
      eventData.filter((item) => item.securityOfficer === "").length,
    );
    setInvestigating(
      eventData.filter((item) => item.status === "investigating").length,
    );
    setBlocked(eventData.filter((item) => item.status === "mitigated").length);
  }, []);

  useEffect(() => {
    const updateEventsPerPage = () => {
      setEventsPerPage(
        window.innerWidth <= 767
          ? eventData.length
          : window.innerWidth <= 1278
            ? 6
            : 16,
      );
      setCurrentPage(1);
    };

    updateEventsPerPage();
    window.addEventListener("resize", updateEventsPerPage);

    return () => {
      window.removeEventListener("resize", updateEventsPerPage);
    };
  }, [eventData.length]);

  const cardsData = [
    {
      header: "Unassigned incidents",
      value: unassigned,
      color: "text-(--critical)",
    },
    {
      header: "Investigating",
      value: investigating,
      color: "text-(--high)",
    },
    {
      header: "Automatically blocked",
      value: blocked,
      color: "text-(--low)",
    },
    {
      header: "Mean time to contain",
      value: "45s",
      color: "text-(--accent)",
    },
  ];
  return (
    <PageLayout
      heading="Security Threat Incidents"
      desc="Correlated incident containers generated by cognitive context checks mapping vectors, hosts, and actors."
    >
      <div className="grid w-full grid-cols-2 gap-2 lg:grid-cols-3 lg:gap-5 xl:grid-cols-4">
        {cardsData.map((card, index) => (
          <Cards key={index} {...card} />
        ))}
      </div>

      {/* Search and stream controls. */}
      <div className="w-full p-3 bg-(--bg-sec) rounded-md border border-(--border) flex flex-col xl:flex-row xl:items-center gap-3">
        {/* search */}
        <div className="w-full p-2 bg-(--bg) border border-(--border) flex items-center justify-start gap-2 rounded-md ">
          <Search size={20} className="text-(--text-sec)" />
          <input
            type="text"
            id="live-search"
            name="live-search"
            placeholder="Filter event type, IP, host..."
            value={searchQuery}
            onChange={(event) => setSearchQuery(event.target.value)}
            className="outline-0 focus:outline-0 leading-0 text-md text-(--text) placeholder:text-(--text-sec) w-full "
          />
        </div>

        {/* filter and buttons */}
        <div className="w-full flex justify-start xl:justify-start gap-2 text-center flex-wrap ">
          {/* filter */}
          <div className="p-2 bg-(--bg) border border-(--border) rounded-md">
            <label
              htmlFor="severity-filter"
              className="text-md font-semibold mr-2"
            >
              Severity :
            </label>

            <select
              name="severity"
              id="severity-filter"
              value={severityFilter}
              onChange={(event) => setSeverityFilter(event.target.value)}
              className="text-md font-semibold focus:outline-0 leading-none"
            >
              <option
                className="bg-(--bg) text-center text-(--text-sec) p-2 border border-(--border) "
                value="all"
              >
                All
              </option>
              <option
                className=" bg-(--bg) text-center text-(--text-sec) p-2 border text-md border-(--border) "
                value="critical"
              >
                Critical
              </option>
              <option
                className="bg-(--bg) text-center text-(--text-sec) p-2 border border-(--border) "
                value="high"
              >
                High
              </option>
              <option
                className="bg-(--bg) text-center text-(--text-sec) p-2 border border-(--border) "
                value="medium"
              >
                Medium
              </option>
              <option
                className="bg-(--bg) text-center text-(--text-sec) p-2 border border-(--border) "
                value="low"
              >
                Low
              </option>
            </select>
          </div>
          <div className="p-2 bg-(--bg) border border-(--border) rounded-md">
            <label htmlFor="status" className="text-md font-semibold mr-2">
              Status :
            </label>

            <select
              name="status"
              id="status"
              value={statusFilter}
              onChange={(event) => setStatusFilter(event.target.value)}
              className="text-md font-semibold focus:outline-0 leading-none"
            >
              <option
                className="bg-(--bg) text-center text-(--text-sec) p-2 border border-(--border) "
                value="all"
              >
                All
              </option>
              <option
                className=" bg-(--bg) text-center text-(--text-sec) p-2 border text-md border-(--border) "
                value="active"
              >
                Active
              </option>
              <option
                className="bg-(--bg) text-center text-(--text-sec) p-2 border border-(--border) "
                value="investigating"
              >
                Investigating
              </option>
              <option
                className="bg-(--bg) text-center text-(--text-sec) p-2 border border-(--border) "
                value="mitigated"
              >
                Mitigated
              </option>
              <option
                className="bg-(--bg) text-center text-(--text-sec) p-2 border border-(--border) "
                value="closed"
              >
                Closed
              </option>
            </select>
          </div>
          <div className="p-2 bg-(--bg) border border-(--border) rounded-md">
            <label
              htmlFor="assignee-filter"
              className="text-md font-semibold mr-2"
            >
              Assignee :
            </label>

            <select
              name="assignee"
              id="assignee-filter"
              value={assigneeFilter}
              onChange={(event) => setAssigneeFilter(event.target.value)}
              className="text-md font-semibold focus:outline-0 leading-none"
            >
              <option
                className="bg-(--bg) text-center text-(--text-sec) p-2 border border-(--border) "
                value="all"
              >
                All
              </option>
              {hasUnassignedIncidents && (
                <option value={UNASSIGNED_FILTER}>Unassigned</option>
              )}
              {assignees.map((assignee) => (
                <option key={assignee} value={assignee}>
                  {assignee}
                </option>
              ))}
            </select>
          </div>
        </div>
      </div>

      {/* Compact pagination controls for the filtered event collection. */}
      <div className="hidden  md:flex w-full flex-wrap items-center justify-end gap-2">
        {/* previous button */}
        <button
          type="button"
          onClick={() => setCurrentPage((page) => page - 1)}
          disabled={currentPage === 1}
          className="rounded-md border border-(--border) bg-(--bg-sec) px-3 py-2 text-sm font-semibold text-(--text) disabled:cursor-not-allowed disabled:opacity-50"
        >
          Previous
        </button>

        {/* pages button */}
        {visiblePages.map((page) => (
          <button
            key={page}
            type="button"
            onClick={() => setCurrentPage(page)}
            className={`w-9 h-9 rounded-md border text-sm font-semibold ${
              currentPage === page
                ? "border-(--accent) bg-(--accent) text-(--bg-sec)"
                : "border-(--border) bg-(--bg-sec) text-(--text)"
            }`}
          >
            {page}
          </button>
        ))}

        {/* next button */}
        <button
          type="button"
          onClick={() => setCurrentPage((page) => page + 1)}
          disabled={currentPage === totalPages || totalPages === 0}
          className="rounded-md border border-(--border) bg-(--bg-sec) px-3 py-2 text-sm font-semibold text-(--text) disabled:cursor-not-allowed disabled:opacity-50"
        >
          Next
        </button>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-2 xl:grid-cols-4 gap-4">
        {currentEvents.map((event) => (
          <EventCard key={event.id} data={event} varient="incident" />
        ))}
      </div>
    </PageLayout>
  );
}

export default Incidents;
